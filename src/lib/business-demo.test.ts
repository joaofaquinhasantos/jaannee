import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import {
  BUSINESS_DEMO_PLANS,
  MENU_LANGUAGES,
  businessDemoMenu,
  businessDemoRestaurant,
  createEmptyDemoMenuItem,
  planHasFeature,
  previewQrImageUrl,
  sampleQrDestination,
  validateBusinessDraft,
} from "./business-demo";

describe("restaurant Free-to-Pro development demo", () => {
  it("keeps free profile/menu/QR available but gates assisted translation and outreach", () => {
    for (const capability of ["restaurant_page", "menu_editor", "basic_qr"] as const) {
      expect(planHasFeature("free", capability)).toBe(true);
    }
    expect(planHasFeature("free", "ai_translation")).toBe(false);
    expect(planHasFeature("free", "vouchers")).toBe(false);
    expect(planHasFeature("pro", "ai_translation")).toBe(true);
    expect(planHasFeature("pro", "qr_branding")).toBe(true);
    expect(planHasFeature("pro", "vouchers")).toBe(false);
    expect(planHasFeature("growth", "vouchers")).toBe(true);
    expect(planHasFeature("growth", "loyalty")).toBe(true);
    expect(BUSINESS_DEMO_PLANS.free.priceThb).toBe(0);
  });

  it("provides all sample menu translations but does not imply AI executed", () => {
    expect(businessDemoMenu.length).toBeGreaterThanOrEqual(5);
    for (const item of businessDemoMenu) {
      expect(item.available).toBe(true);
      expect(item.priceThb).toBeGreaterThan(0);
      for (const lang of MENU_LANGUAGES) {
        expect(item.names[lang].length).toBeGreaterThan(0);
        expect(item.descriptions[lang].length).toBeGreaterThan(0);
      }
    }
    const item = createEmptyDemoMenuItem(5);
    expect(item.id).toBe("draft-5");
    expect(item.names.en).toBe("");
    expect(item.priceThb).toBe(0);
  });

  it("validates basic business details without contacting the real backend", () => {
    expect(validateBusinessDraft(businessDemoRestaurant)).toBeNull();
    expect(validateBusinessDraft({ ...businessDemoRestaurant, name: "A" })).toMatch(/three characters/);
    expect(validateBusinessDraft({ ...businessDemoRestaurant, area: " " })).toMatch(/area/);
    expect(validateBusinessDraft({ ...businessDemoRestaurant, cuisine: "" })).toMatch(/cuisine/);
  });

  it("encodes a valid, public fixed sample URL into a scannable external QR", () => {
    const destination = sampleQrDestination("https://example.com");
    const link = new URL(destination);
    expect(link.hostname).toBe("example.com");
    expect(link.pathname).toBe("/demo-business");
    expect(link.searchParams.get("screen")).toBe("preview");
    expect(link.searchParams.get("sample")).toBe("1");
    const qr = new URL(previewQrImageUrl(destination, true));
    expect(qr.origin).toBe("https://quickchart.io");
    expect(qr.pathname).toBe("/qr");
    expect(qr.searchParams.get("text")).toBe(destination);
    expect(qr.searchParams.get("format")).toBe("svg");
    expect(qr.searchParams.get("margin")).toBe("4");
    expect(() => sampleQrDestination("javascript:alert(1)")).toThrow(/HTTP/);
  });

  it("uses demo-only route and never calls Supabase, billing or real AI services", () => {
    const src = readFileSync(new URL("../routes/demo-business.tsx", import.meta.url), "utf8");
    const root = readFileSync(new URL("../routes/__root.tsx", import.meta.url), "utf8");
    const diner = readFileSync(new URL("../routes/demo.tsx", import.meta.url), "utf8");
    expect(src).toContain('createFileRoute("/demo-business")');
    expect(src).toContain('"noindex, nofollow, noarchive"');
    expect(src).toContain("No real restaurant page");
    expect(src).toContain("Sample translations are prewritten, not generated by AI");
    expect(src).toContain("Thai dish name (manual)");
    expect(src).toContain("Sponsored boosts");
    expect(src).toContain("Pricing TBD");
    expect(src).not.toMatch(/createServerFn|supabase\.|stripe\.|openai\.|fetch\(/);
    expect(root).toContain('pathname === "/demo-business"');
    expect(diner).toContain('to="/demo-business"');
  });
});
